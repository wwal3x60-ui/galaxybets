CREATE TABLE IF NOT EXISTS gbSlotWalletRemainders (
 userId BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 units INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS gbSlotSessions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 userId BIGINT UNSIGNED NOT NULL,
 gameId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 currency CHAR(3) NOT NULL,
 state VARCHAR(20) NOT NULL DEFAULT 'pending',
 createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX byPlayerGame(userId,gameId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS gbSlotRounds (
 appId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 roundId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 userId BIGINT UNSIGNED NOT NULL,
 gameId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 currency CHAR(3) NOT NULL,
 betTotal DECIMAL(20,4) NOT NULL DEFAULT 0,
 winTotal DECIMAL(20,4) NOT NULL DEFAULT 0,
 refundTotal DECIMAL(20,4) NOT NULL DEFAULT 0,
 closed TINYINT NOT NULL DEFAULT 0,
 createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(appId,roundId), INDEX byPlayer(userId,createdAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS gbSlotTransactions (
 appId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 transactionId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 roundId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 userId BIGINT UNSIGNED NOT NULL,
 gameId VARCHAR(191) COLLATE utf8mb4_bin NOT NULL,
 reason VARCHAR(10) NOT NULL,
 amount DECIMAL(20,4) NOT NULL,
 payloadHash CHAR(64) NOT NULL,
 response JSON NOT NULL,
 refunded TINYINT NOT NULL DEFAULT 0,
 createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(appId,transactionId), INDEX byPlayer(userId,createdAt), INDEX byRound(appId,roundId)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
