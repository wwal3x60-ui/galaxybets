export function cleanedDropImage(src: unknown): string {
  const value = typeof src === "string" ? src.trim() : "";
  const match = value.match(/^(.*\/public\/)drop-images\/([^/?#]+)(?:[?#].*)?$/);
  if (!match || !cutouts[match[2]]) return optimizedCatalogImage(value);
  return optimizedCatalogImage(`${match[1]}drop-cutouts/${cutouts[match[2]]}`);
}
