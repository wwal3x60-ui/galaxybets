CREATE TABLE IF NOT EXISTS cs2CaseCommitments (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 userId BIGINT UNSIGNED NOT NULL, caseSlug VARCHAR(64) NOT NULL,
 caseVersion CHAR(64) CHARACTER SET ascii NOT NULL, quantity TINYINT UNSIGNED NOT NULL,
 serverSeed CHAR(64) CHARACTER SET ascii NOT NULL, serverSeedHash CHAR(64) CHARACTER SET ascii NOT NULL,
 expiresAt DATETIME(3) NOT NULL, usedRequestId CHAR(36) CHARACTER SET ascii DEFAULT NULL,
 createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), KEY idx_cs2_commit_owner(userId,createdAt), KEY idx_cs2_commit_expiry(userId,usedRequestId,expiresAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cs2CaseRequests (
 userId BIGINT UNSIGNED NOT NULL, requestId CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 fingerprint CHAR(64) CHARACTER SET ascii NOT NULL, receipt JSON NOT NULL,
 createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), PRIMARY KEY(userId,requestId), KEY idx_cs2_history(userId,createdAt)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS cs2CaseResults (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, userId BIGINT UNSIGNED NOT NULL,
 requestId CHAR(36) CHARACTER SET ascii NOT NULL, itemIndex TINYINT UNSIGNED NOT NULL,
 caseSlug VARCHAR(64) NOT NULL, skinId VARCHAR(64) NOT NULL, name VARCHAR(255) NOT NULL, img MEDIUMTEXT NOT NULL,
 price DECIMAL(18,2) NOT NULL, status VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE',
 createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), soldAt DATETIME(3) DEFAULT NULL,
 UNIQUE KEY uq_cs2_request_item(userId,requestId,itemIndex), KEY idx_cs2_inventory(userId,status,id)
) ENGINE=InnoDB;
